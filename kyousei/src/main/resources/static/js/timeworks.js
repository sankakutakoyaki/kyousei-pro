function getDailyPayForm(items) {
    const area = document.getElementById('print-dialog-area');
    // const area = document.createElement('div');
    // area.classList.add('dialog');
    // area.insertAdjacentElement('beforeend', elm)

    let i = 0;
    let tbl = "";
    items.forEach(item => {
        i++;
        if (i % 2 == 1){
            tbl = document.createElement('table');
            tbl.classList.add('print-table', 'dailypay');
            // tbl.classList.add('print-table', 'timeworks');
            createDailyPayForm(tbl, item, "(受領者控え)");
            createDailyPayForm(tbl, item, "(自社控え)");
        } else {
            createDailyPayForm(tbl, item, "(受領者控え)");
            createDailyPayForm(tbl, item, "(自社控え)");
            area.insertAdjacentElement('beforeend', tbl);
        }

        if (i % 2 == 1 && i == items.length) {
            let cell = tbl.insertRow();
            cell.classList.add('space-cell');
        }

        if (i % 2 == 0 || (i % 2 == 1 && i == items.length)) {
            area.insertAdjacentElement('beforeend', tbl);
        }
    });    
}

